    #[test]
    fn generated_assets_join_the_catalog() {
        let mut c = sample();
        let before = c.assets.len();
        let items = vec![
            GeneratedAsset {
                job_id: "j1".into(),
                kind: "mesh".into(),
                title: "Mossy Stone Lantern".into(),
                target_project: Some("PrjEfz".into()),
                unreal_object_path: Some("/Game/Gen/SM_Lantern".into()),
                output_path: Some("F:/out/lantern".into()),
                class: Some("StaticMesh".into()),
                description: None,
                category: None,
                completed_at: None,
                extra_tags: vec!["size:medium".into()],
                details: serde_json::json!({}),
            },
            GeneratedAsset {
                job_id: "j2".into(),
                kind: "sound".into(),
                title: "Door creak".into(),
                target_project: None,
                unreal_object_path: None,
                output_path: None,
                class: Some("SoundWave".into()),
                description: Some("a wooden door creaking".into()),
                category: Some("SFX".into()),
                completed_at: None,
                extra_tags: vec![],
                details: serde_json::Value::Null,
            },
        ];
        c.add_generated(&items);
        c.add_generated(&items); // idempotent
        assert_eq!(c.assets.len(), before + 2);
        let i = c.find_asset("gen:j1").unwrap();
        assert_eq!(c.assets[i].source, SourceKind::Generated);
        assert!(c.asset_has_tag(&c.assets[i], "source:generated"));
        assert!(c.asset_has_tag(&c.assets[i], "size:medium"));
        let q = |t: &str| crate::search::SearchQuery {
            text: t.into(),
            ..Default::default()
        };
        let hits = c.search(&q("lantern"));
        assert_eq!(hits.total, 1);
        assert_eq!(c.assets[hits.hits[0].asset].id, "gen:j1");
        // The prompt is searchable and `source:generated` filters to them.
        assert_eq!(c.search(&q("creaking")).total, 1);
        assert_eq!(c.search(&q("source:generated")).total, 2);
        // Pack kinds never include generated assets; the `generated` pack filter finds them.
        let mut qq = q("");
        qq.kind = Some("content".into());
        assert_eq!(c.search(&qq).total, before);
        let mut qq = q("");
        qq.pack = Some("generated".into());
        assert_eq!(c.search(&qq).total, 2);
        assert!(c.find_asset("gen:nope").is_none());
    }

