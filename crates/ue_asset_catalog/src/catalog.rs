    #[test]
    fn thumbnails_are_cached_on_disk_not_on_the_share() {
        // No thumbnail flag: Ok(None) without touching any zip.
        let c = sample();
        assert_eq!(
            c.thumbnail("aaaaaaaaaaaa:/Game/Nature/SM_Rock").unwrap(),
            None
        );
        assert!(c.thumbnail("zzzz:/Game/X").is_err());
        // A cached file is served without opening the (fake) zip.
        let t = crate::testutil::Tmp::new();
        let mut e = sidecar("Thumbs", SHA_A, Some("5.3"), Kind::Content);
        e.zip_path = t.path().join("share/thumbs.aaaaaaaaaaaa.zip");
        let mut p = pkg("/Game/T/SM_T", "StaticMesh", &[]);
        p.has_thumbnail = true;
        let mut c = Catalog::from_entries(vec![(e, IndexOutcome::Indexed(index(SHA_A, vec![p])))]);
        c.thumb_dir = Some(t.path().join("cache/thumbs"));
        let id = c.assets[0].id.clone();
        assert!(c.thumbnail(&id).is_err()); // zip missing: read fails, nothing cached
        let file = c
            .thumb_dir
            .as_ref()
            .unwrap()
            .join("aaaaaaaaaaaa")
            .join(format!("{:016x}_SM_T.img", fnv1a(b"/game/t/sm_t")));
        write_atomic(&file, b"\x89PNGfake").unwrap();
        assert_eq!(c.thumbnail(&id).unwrap().unwrap(), b"\x89PNGfake");
        assert!(!t
            .path()
            .join("share")
            .join("thumbs.aaaaaaaaaaaa.zip.thumb")
            .exists());
    }

