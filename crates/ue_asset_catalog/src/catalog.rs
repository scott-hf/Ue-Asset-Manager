// Loading from library directories (overlay, local cache, build on demand)
// ---------------------------------------------------------------------------------------------

#[derive(Clone, Debug)]
pub struct LoadOptions {
    /// Build indexes that have no valid overlay (reads the zips; slow over SMB). Off = only use
    /// overlays and the cache and report the rest as failed.
    pub build_missing: bool,
    /// Startup cache file (`<cache dir>/ue_asset_catalog/catalog.json`).
    pub cache_path: Option<PathBuf>,
    pub threads: usize,
    /// Also write a freshly built index as the `.assets.json` overlay next to the zip (best
    /// effort). Off by default: the catalog keeps built indexes in its local cache and the
    /// server never writes into the library unless asked.
    pub write_overlays: bool,
}

impl Default for LoadOptions {
    fn default() -> Self {
        LoadOptions {
            build_missing: true,
            cache_path: None,
            threads: 4,
            write_overlays: false,
        }
    }
}

#[derive(Clone, Debug, Default, Serialize)]
pub struct LoadReport {
    pub entries: usize,
    pub from_cache: usize,
    pub from_overlay: usize,
    pub built: usize,
    pub skipped_plugins: usize,
    pub failed: Vec<(String, String)>,
    pub warnings: Vec<String>,
    pub cache_written: bool,
    pub elapsed_ms: u128,
}

#[derive(Serialize, Deserialize)]
struct CacheFile {
    schema: u32,
    packs: HashMap<String, CacheEntry>,
}

#[derive(Serialize, Deserialize)]
struct CacheEntry {
    key: String,
    index: AssetIndex,
}

const CACHE_SCHEMA: u32 = 1;

#[derive(Clone, Copy, PartialEq, Eq)]
enum Origin {
    Cache,
    Overlay,
    Built,
}

/// A library dir given on the command line may be the share root: use its `library` subfolder
/// when the dir itself holds no sidecars (same rule as the app's `library_dir_of`).
pub fn resolve_library_dir(dir: &Path) -> PathBuf {
    if scan_library(dir).is_empty() {
        let sub = dir.join("library");
        if sub.is_dir() {
            return sub;
        }
    }
    dir.to_path_buf()
}

fn mtime_secs(m: &fs::Metadata) -> u64 {
    m.modified()
        .ok()
        .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
        .map_or(0, |d| d.as_secs())
}

/// Cache key: the overlay's size and mtime, or the zip's when there is no overlay.
fn index_key(entry: &LibraryEntry) -> String {
    if let Ok(m) = fs::metadata(index_path(entry)) {
        return format!("o:{}:{}", m.len(), mtime_secs(&m));
    }
    match fs::metadata(&entry.zip_path) {
        Ok(m) => format!("z:{}:{}", m.len(), mtime_secs(&m)),
        Err(_) => "none".to_string(),
    }
}

fn is_fresh(entry: &LibraryEntry, idx: &AssetIndex) -> bool {
    idx.schema == INDEX_SCHEMA
        && idx.sidecar_sha256 == entry.sidecar.sha256
        && idx.entry_count == entry.sidecar.entry_count
}

fn read_overlay(entry: &LibraryEntry) -> Option<AssetIndex> {
    let text = fs::read_to_string(index_path(entry)).ok()?;
    let idx: AssetIndex = serde_json::from_str(text.trim_start_matches('\u{feff}')).ok()?;
    is_fresh(entry, &idx).then_some(idx)
}

fn load_one(
    entry: &LibraryEntry,
    cache: &HashMap<String, CacheEntry>,
    opts: &LoadOptions,
) -> (Result<AssetIndex, String>, Origin, String) {
    let key = index_key(entry);
    if let Some(c) = cache.get(&pack_id_of(entry)) {
        if c.key == key && is_fresh(entry, &c.index) {
            return (Ok(c.index.clone()), Origin::Cache, key);
        }
    }
    if let Some(idx) = read_overlay(entry) {
        return (Ok(idx), Origin::Overlay, key);
    }
    if !opts.build_missing {
        return (
            Err("no valid asset index overlay (index building is off)".to_string()),
            Origin::Overlay,
            key,
        );
    }
    let built = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        if opts.write_overlays {
            load_or_build_index(entry)
        } else {
            build_index(entry)
        }
    }));
    match built {
        Ok(Ok(idx)) => {
            let key = index_key(entry);
            (Ok(idx), Origin::Built, key)
        }
        Ok(Err(e)) => (Err(e.to_string()), Origin::Built, key),
        Err(_) => (
            Err("index builder panicked".to_string()),
            Origin::Built,
            key,
        ),
    }
}

fn read_cache(path: &Path) -> HashMap<String, CacheEntry> {
    let Ok(text) = fs::read_to_string(path) else {
        return HashMap::new();
    };
    match serde_json::from_str::<CacheFile>(&text) {
        Ok(c) if c.schema == CACHE_SCHEMA => c.packs,
        _ => HashMap::new(), // corrupt or other schema: ignored, rewritten later
    }
}

/// FNV-1a 64 (stable across Rust versions).
fn fnv1a(data: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in data {
        h ^= u64::from(*b);
        h = h.wrapping_mul(0x0100_0000_01b3);
    }
    h
}

fn write_atomic(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    let mut tmp = path.as_os_str().to_os_string();
    tmp.push(format!(".tmp-{}", std::process::id()));
    let tmp = PathBuf::from(tmp);
    fs::write(&tmp, bytes)?;
    fs::rename(&tmp, path).inspect_err(|_| {
        let _ = fs::remove_file(&tmp);
    })
}

fn write_cache(path: &Path, packs: HashMap<String, CacheEntry>) -> std::io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    let bytes = serde_json::to_vec(&CacheFile {
        schema: CACHE_SCHEMA,
        packs,
    })?;
    let mut tmp = path.as_os_str().to_os_string();
    tmp.push(format!(".tmp-{}", std::process::id()));
    let tmp = PathBuf::from(tmp);
    fs::write(&tmp, bytes)?;
    fs::rename(&tmp, path).inspect_err(|_| {
        let _ = fs::remove_file(&tmp);
    })
}

/// Hash of the library dirs' zip, sidecar and overlay names, sizes and mtimes. A change means
/// the catalog should be reloaded.
pub fn fingerprint(dirs: &[PathBuf]) -> u64 {
    let mut rows: Vec<(String, u64, u64)> = Vec::new();
    for d in dirs {
        let Ok(rd) = fs::read_dir(d) else {
            rows.push((format!("unreadable:{}", d.display()), 0, 0));
            continue;
        };
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().to_string();
            let low = name.to_ascii_lowercase();
            if name.starts_with(".tmp-")
                || !(low.ends_with(".zip.json")
                    || low.ends_with(".zip.assets.json")
                    || low.ends_with(".zip.vision.json")
                    || low.ends_with(".zip"))
            {
                continue;
            }
            let (len, mt) = e.metadata().map_or((0, 0), |m| (m.len(), mtime_secs(&m)));
            rows.push((format!("{}/{}", d.display(), name), len, mt));
        }
    }
    rows.sort();
    let mut h = DefaultHasher::new();
    rows.hash(&mut h);
    h.finish()
}

impl Catalog {
    /// Scan the library dirs and load every pack's index (cache, overlay, or build).
    pub fn load(dirs: &[PathBuf], opts: &LoadOptions) -> (Catalog, LoadReport) {
        let t0 = Instant::now();
        let mut report = LoadReport::default();
        let mut resolved: Vec<PathBuf> = Vec::new();
        for d in dirs {
            let r = resolve_library_dir(d);
            if !r.is_dir() {
                report
                    .warnings
                    .push(format!("library dir not reachable: {}", d.display()));
            }
            if !resolved.contains(&r) {
                resolved.push(r);
            }
        }
        let fp = fingerprint(&resolved);
        let mut entries: Vec<LibraryEntry> = Vec::new();
        for d in &resolved {
            entries.extend(scan_library(d));
        }
        report.entries = entries.len();

        let cache = opts
            .cache_path
            .as_deref()
            .map(read_cache)
            .unwrap_or_default();

        // Plugins are never indexed; everything else is loaded in parallel (SMB latency).
        let work: Vec<usize> = entries
            .iter()
            .enumerate()
            .filter(|(_, e)| e.sidecar.kind != Kind::Plugin)
            .map(|(i, _)| i)
            .collect();
        type Slot = Option<(Result<AssetIndex, String>, Origin, String)>;
        let slots: Vec<Mutex<Slot>> = work.iter().map(|_| Mutex::new(None)).collect();
        let next = AtomicUsize::new(0);
        let threads = opts.threads.clamp(1, 16).min(work.len().max(1));
        std::thread::scope(|s| {
            for _ in 0..threads {
                s.spawn(|| loop {
                    let n = next.fetch_add(1, Ordering::SeqCst);
                    if n >= work.len() {
                        break;
                    }
                    let r = load_one(&entries[work[n]], &cache, opts);
                    *slots[n].lock().unwrap_or_else(|p| p.into_inner()) = Some(r);
                });
            }
        });

        let mut outcomes: Vec<(LibraryEntry, IndexOutcome)> = Vec::new();
        let mut new_cache: HashMap<String, CacheEntry> = HashMap::new();
        let mut loaded: HashMap<usize, (Result<AssetIndex, String>, Origin, String)> =
            HashMap::new();
        for (n, slot) in slots.into_iter().enumerate() {
            if let Some(r) = slot.into_inner().unwrap_or_else(|p| p.into_inner()) {
                loaded.insert(work[n], r);
            }
        }
        for (i, entry) in entries.into_iter().enumerate() {
            if entry.sidecar.kind == Kind::Plugin {
                report.skipped_plugins += 1;
                outcomes.push((
                    entry,
                    IndexOutcome::NotIndexable("plugins are not browsable".to_string()),
                ));
                continue;
            }
            let id = pack_id_of(&entry);
            match loaded.remove(&i) {
                Some((Ok(idx), origin, key)) => {
                    match origin {
                        Origin::Cache => report.from_cache += 1,
                        Origin::Overlay => report.from_overlay += 1,
                        Origin::Built => report.built += 1,
                    }
                    new_cache.insert(
                        id,
                        CacheEntry {
                            key,
                            index: idx.clone(),
                        },
                    );
                    outcomes.push((entry, IndexOutcome::Indexed(idx)));
                }
                Some((Err(e), _, _)) => {
                    report
                        .failed
                        .push((entry.sidecar.display_name.clone(), e.clone()));
                    outcomes.push((entry, IndexOutcome::Failed(e)));
                }
                None => {
                    outcomes.push((entry, IndexOutcome::Failed("index load aborted".into())));
                }
            }
        }
        if let Some(path) = &opts.cache_path {
            if report.from_cache != new_cache.len() || cache.len() != new_cache.len() {
                match write_cache(path, new_cache) {
                    Ok(()) => report.cache_written = true,
                    Err(e) => report
                        .warnings
                        .push(format!("could not write cache {}: {e}", path.display())),
                }
            }
        }
        // Optional vision overlays (`<zip>.vision.json`): tiny, read when present.
        let mut vis: HashMap<String, VisionOverlay> = HashMap::new();
        for (entry, outcome) in &outcomes {
            if matches!(outcome, IndexOutcome::Indexed(_)) {
                if let Some(v) = vision::load(entry) {
                    vis.insert(pack_id_of(entry), v);
                }
            }
        }
        let mut catalog = Catalog::from_entries_with_vision(outcomes, vis);
        catalog.dirs = resolved;
        catalog.thumb_dir = opts
            .cache_path
            .as_deref()
            .and_then(Path::parent)
            .map(|d| d.join("thumbs"));
        catalog.fingerprint = fp;
        report.elapsed_ms = t0.elapsed().as_millis();
        (catalog, report)
    }

    /// Counts per kind, class, source, engine version and pack: one pass over the assets, cheap
    /// enough to call whenever a filter UI needs refreshing.
    pub fn facets(&self) -> Facets {
        self.facets_excluding(&[])
    }

    /// [`Catalog::facets`] without the pack families whose slug is in `exclude_packs` (the same
    /// identity as `SearchQuery::exclude_packs`). Excluded packs are also omitted from the pack
    /// list; call [`Catalog::facets`] for the full list a pack dropdown needs.
    pub fn facets_excluding(&self, exclude_packs: &[String]) -> Facets {
        let excluded = self.excluded_families(exclude_packs);
        let mut f = Facets::default();
        let mut per_family = vec![0usize; self.families.len()];
        for a in self.assets.iter().filter(|a| !excluded.contains(&a.family)) {
            *f.kinds.entry(a.kind.to_string()).or_insert(0) += 1;
            *f.classes
                .entry(a.class.clone().unwrap_or_else(|| "unknown".to_string()))
                .or_insert(0) += 1;
            let src = if a.source == SourceKind::Generated {
                "generated"
            } else {
                "pack"
            };
            *f.sources.entry(src.to_string()).or_insert(0) += 1;
            per_family[a.family] += 1;
            let mut seen: Vec<String> = Vec::new();
            for r in &a.releases {
                if let Some(l) = self.packs[r.pack].engine_label() {
                    if !seen.contains(&l) {
                        seen.push(l);
                    }
                }
            }
            for l in seen {
                *f.engine_versions.entry(l).or_insert(0) += 1;
            }
        }
        for (fi, fam) in self.families.iter().enumerate() {
            if per_family[fi] == 0 {
                continue;
            }
            f.packs.push(PackFacet {
                name: fam.name.clone(),
                slug: fam.slug.clone(),
                kind: if fam.source == SourceKind::Generated {
                    "generated".to_string()
                } else {
                    match fam.kind {
                        Kind::Content => "content",
                        Kind::Plugin => "plugin",
                        Kind::Project => "project",
                    }
                    .to_string()
                },
                assets: per_family[fi],
            });
        }
        f.packs
            .sort_by(|a, b| b.assets.cmp(&a.assets).then_with(|| a.name.cmp(&b.name)));
        f
    }

    /// The editor thumbnail (PNG/JPEG bytes) of an asset, newest release first. Cached on disk under
    /// `thumb_dir` keyed by pack sha12 and game path, so repeated calls never reopen the zip; the
    /// library share is never written. `Ok(None)`: the asset has no stored thumbnail.
    pub fn thumbnail(&self, id: &str) -> Result<Option<Vec<u8>>, String> {
        let ai = self
            .find_asset(id)
            .ok_or_else(|| format!("unknown asset `{id}`"))?;
        let a = &self.assets[ai];
        for r in &a.releases {
            let Some(pk) = self.package(*r) else { continue };
            if !pk.has_thumbnail {
                continue;
            }
            let pack = &self.packs[r.pack];
            let file = self.thumb_dir.as_ref().map(|d| {
                d.join(&pack.id).join(format!(
                    "{:016x}_{}.img",
                    fnv1a(pk.game_path.to_ascii_lowercase().as_bytes()),
                    tags::name_of(&pk.game_path)
                        .chars()
                        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
                        .take(40)
                        .collect::<String>()
                ))
            });
            if let Some(f) = &file {
                if let Ok(bytes) = fs::read(f) {
                    if !bytes.is_empty() {
                        return Ok(Some(bytes));
                    }
                }
            }
            match ue_asset_library::read_thumbnail(&pack.entry, &pk.game_path) {
                Ok(Some(bytes)) => {
                    if let Some(f) = &file {
                        let _ = write_atomic(f, &bytes); // best effort
                    }
                    return Ok(Some(bytes));
                }
                Ok(None) => continue,
                Err(e) => return Err(e.to_string()),
            }
        }
        Ok(None)
    }

    /// Has anything in the library dirs changed since this catalog was loaded?
    pub fn needs_reload(&self) -> bool {
        !self.dirs.is_empty() && fingerprint(&self.dirs) != self.fingerprint
    }
}

