//! The catalog: every asset of every indexed library pack, grouped into pack families,
//! auto-tagged and searchable in memory. Derived data only; the library zips and their
//! `.assets.json` overlays stay the source of truth.
//!
//! Source model: an [`Asset`] has a [`SourceKind`]. Only `Pack` exists today. A second source
//! (generated meshes/sounds) can add assets with `SourceKind::Generated` and ids namespaced
//! `gen:<jobId>`; pack asset ids are `<pack sha12>:<game_path>`.

