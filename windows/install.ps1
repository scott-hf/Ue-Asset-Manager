<#
.SYNOPSIS
  Build (optional), bundle and install Epic Asset Manager on Windows, with a Start Menu shortcut.

.DESCRIPTION
  Per-user install, no admin needed. Requires MSYS2 UCRT64 (GTK4 + libadwaita) and the Rust GNU
  toolchain only to BUILD; the installed copy is self-contained.

  Layout installed to %LOCALAPPDATA%\Programs\EpicAssetManager:
    bin\    epic_asset_manager.exe, ue_asset_sanitizer.exe, GTK/libadwaita DLLs, resources.gresource
    share\  glib schemas (incl. this app's), icon themes
    lib\    gdk-pixbuf loaders

.PARAMETER SkipBuild   Reuse target\release binaries instead of running cargo build --release.
.PARAMETER Msys        MSYS2 root (default C:\msys64).
.PARAMETER InstallDir  Install location.
.PARAMETER Uninstall   Remove the install dir and shortcuts.
#>
param(
    [switch]$SkipBuild,
    [switch]$Uninstall,
    [string]$Msys = 'C:\msys64',
    [string]$InstallDir = (Join-Path $env:LOCALAPPDATA 'Programs\EpicAssetManager')
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$appId = 'io.github.achetagames.epic_asset_manager.Devel'   # must match src/config.rs APP_ID
$startMenu = Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs'
$lnk = Join-Path $startMenu 'Epic Asset Manager.lnk'

if ($Uninstall) {
    Remove-Item $lnk -ErrorAction SilentlyContinue
    if (Test-Path $InstallDir) { Remove-Item $InstallDir -Recurse -Force }
    Write-Host "Removed $InstallDir and the Start Menu shortcut."
    return
}

$ucrt = Join-Path $Msys 'ucrt64'
if (-not (Test-Path "$ucrt\bin\gtk4-update-icon-cache.exe") -and -not (Test-Path "$ucrt\bin\libgtk-4-1.dll")) {
    throw "GTK4 not found under $ucrt. Install: pacman -S mingw-w64-ucrt-x86_64-gtk4 mingw-w64-ucrt-x86_64-libadwaita"
}
$env:PATH = "$ucrt\bin;$env:USERPROFILE\.cargo\bin;$env:PATH"

# --- 1. config.rs (generated by Meson on Linux; hand-written here, gitignored) ---
$cfg = Join-Path $repo 'src\config.rs'
if (-not (Test-Path $cfg)) {
    $ver = ((Select-String -Path (Join-Path $repo 'Cargo.toml') -Pattern '^version\s*=\s*"([^"]+)"' | Select-Object -First 1).Matches[0].Groups[1].Value)
    @"
pub const APP_ID: &str = "$appId";
pub const GETTEXT_PACKAGE: &str = "epic_asset_manager";
pub const LOCALEDIR: &str = "po";
pub const PKGDATADIR: &str = "data/resources";
pub const PROFILE: &str = "Devel";
pub const RESOURCES_FILE: &str = "data/resources/resources.gresource";
pub const VERSION: &str = "$ver-devel";
"@ | Set-Content -Encoding ascii $cfg
}

# --- 2. gresource (always rebuild: UI files change) ---
Push-Location (Join-Path $repo 'data\resources')
glib-compile-resources --target=resources.gresource resources.gresource.xml
if ($LASTEXITCODE) { throw 'glib-compile-resources failed' }
Pop-Location

# --- 3. build ---
Push-Location $repo
if (-not $SkipBuild) {
    cargo build --release --workspace
    if ($LASTEXITCODE) { throw 'cargo build failed' }
}
Pop-Location
$exe = Join-Path $repo 'target\release\epic_asset_manager.exe'
$san = Join-Path $repo 'target\release\ue_asset_sanitizer.exe'
if (-not (Test-Path $exe)) { throw "Missing $exe (run without -SkipBuild)" }

# --- 4. stage into the install dir ---
Get-Process epic_asset_manager -ErrorAction SilentlyContinue |
    Where-Object { $_.Path -like "$InstallDir*" } | Stop-Process -Force
$bin = Join-Path $InstallDir 'bin'
New-Item -ItemType Directory -Force $bin | Out-Null
Copy-Item $exe $bin -Force
if (Test-Path $san) { Copy-Item $san $bin -Force }
Copy-Item (Join-Path $repo 'data\resources\resources.gresource') $bin -Force
Copy-Item (Join-Path $repo 'data\icons\io.github.achetagames.epic_asset_manager.ico') $InstallDir -Force

# DLL closure via ldd (MSYS2); keep only files that live under ucrt64
$ldd = Join-Path $Msys 'usr\bin\ldd.exe'
$dlls = & $ldd $exe | ForEach-Object { if ($_ -match '=> (/ucrt64/[^ ]+\.dll)') { $Matches[1] } } | Sort-Object -Unique
foreach ($d in $dlls) {
    Copy-Item (Join-Path $Msys ($d.TrimStart('/') -replace '/', '\')) $bin -Force
}

# gdk-pixbuf loaders (+ their DLL deps) and a relocatable cache
$pbSrc = Join-Path $ucrt 'lib\gdk-pixbuf-2.0\2.10.0'
$pbDst = Join-Path $InstallDir 'lib\gdk-pixbuf-2.0\2.10.0'
New-Item -ItemType Directory -Force "$pbDst\loaders" | Out-Null
Copy-Item "$pbSrc\loaders\*.dll" "$pbDst\loaders" -Force
foreach ($l in Get-ChildItem "$pbDst\loaders\*.dll") {
    & $ldd $l.FullName | ForEach-Object { if ($_ -match '=> (/ucrt64/[^ ]+\.dll)') { $Matches[1] } } | Sort-Object -Unique | ForEach-Object {
        $src = Join-Path $Msys ($_.TrimStart('/') -replace '/', '\')
        if (-not (Test-Path (Join-Path $bin (Split-Path $src -Leaf)))) { Copy-Item $src $bin -Force }
    }
}
$env:GDK_PIXBUF_MODULEDIR = "$pbDst\loaders"
& (Join-Path $ucrt 'bin\gdk-pixbuf-query-loaders.exe') (Get-ChildItem "$pbDst\loaders\*.dll" | ForEach-Object FullName) |
    ForEach-Object { $_ -replace [regex]::Escape(($InstallDir -replace '\\', '/')), '..' } |
    Set-Content -Encoding utf8 "$pbDst\loaders.cache"

# GSettings schemas: system schemas + this app's, compiled
$schDst = Join-Path $InstallDir 'share\glib-2.0\schemas'
New-Item -ItemType Directory -Force $schDst | Out-Null
Copy-Item (Join-Path $ucrt 'share\glib-2.0\schemas\*.xml') $schDst -Force
(Get-Content (Join-Path $repo 'data\io.github.achetagames.epic_asset_manager.gschema.xml.in') -Raw) `
    -replace '@app-id@', $appId -replace '@gettext-package@', 'epic_asset_manager' |
    Set-Content -Encoding utf8 (Join-Path $schDst "$appId.gschema.xml")
glib-compile-schemas $schDst
if ($LASTEXITCODE) { throw 'glib-compile-schemas failed' }

# Icon themes (symbolic icons used by GTK/libadwaita)
foreach ($t in 'Adwaita', 'hicolor') {
    $s = Join-Path $ucrt "share\icons\$t"
    if (Test-Path $s) { Copy-Item $s (Join-Path $InstallDir 'share\icons') -Recurse -Force }
}

# --- 5. Start Menu shortcut ---
$ws = New-Object -ComObject WScript.Shell
$sc = $ws.CreateShortcut($lnk)
$sc.TargetPath = Join-Path $bin 'epic_asset_manager.exe'
$sc.WorkingDirectory = $bin
$sc.IconLocation = Join-Path $InstallDir 'io.github.achetagames.epic_asset_manager.ico'
$sc.Description = 'Unofficial Epic Games Store client for Unreal Engine assets'
$sc.Save()

Write-Host "Installed to $InstallDir"
Write-Host "Start Menu shortcut: $lnk"
